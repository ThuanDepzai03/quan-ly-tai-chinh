function translateEnglish(text: string): string {
  const exact = ENGLISH[text];
  if (exact) return exact;
  if (text.startsWith('Thu nhập tính thuế × ')) {
    return `Taxable income × ${text.slice('Thu nhập tính thuế × '.length)}`;
  }
  if (text.startsWith('Doanh thu kỳ × ')) {
    return `Period revenue × ${text.slice('Doanh thu kỳ × '.length)}`;
  }
  if (text.startsWith('Lợi nhuận tính thuế × ')) {
    return `Taxable profit × ${text.slice('Lợi nhuận tính thuế × '.length).replace('(doanh thu năm chọn bậc thuế)', '(annual revenue determines the tax bracket)')}`;
  }
  if (text.startsWith('Tính lũy tiến trên max(0, thu nhập tháng − ')) {
    return `Progressive calculation on max(0, monthly income − ${text.slice('Tính lũy tiến trên max(0, thu nhập tháng − '.length)}`;
  }
  if (text.startsWith('Doanh thu năm không vượt ngưỡng ')) {
    return text.replace('Doanh thu năm không vượt ngưỡng ', 'Annual revenue does not exceed ')
      .replace('; không tính VAT/TNCN kinh doanh trong ước tính.', '; VAT / business income tax are not estimated.');
  }
  if (text.startsWith('Chưa nhập lợi nhuận tính thuế kỳ;')) {
    return 'Taxable profit for the period was not entered; corporate income tax was not estimated.';
  }
  if (text.startsWith('VAT doanh nghiệp chỉ là ước tính')) {
    return 'Corporate VAT is estimated from the configured rate and deductible input VAT; verify against invoices, goods, and filing method.';
  }
  if (text.startsWith('Bậc thuế TNDN có thể phụ thuộc')) {
    return 'Corporate income tax brackets may depend on prior-period revenue and exclusions or incentives; the app does not check these legal conditions.';
  }
  return text;
}

const PreferencesContext = createContext<Preferences | null>(null);

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [theme, setThemeState] = useState<AppTheme>('light');
  const [language, setLanguageState] = useState<AppLanguage>('vi');
  const [error, setError] = useState('');

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const preferences = JSON.parse(saved) as { theme?: AppTheme; language?: AppLanguage };
        if (preferences.theme === 'light' || preferences.theme === 'dark') setThemeState(preferences.theme);
        if (preferences.language === 'vi' || preferences.language === 'en') setLanguageState(preferences.language);
      }
    } catch (loadError) {
      setError(`Could not load preferences: ${loadError instanceof Error ? loadError.message : String(loadError)}`);
    }
  }, []);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.lang = language;
    document.title = language === 'en' ? ENGLISH['Quản lý tài chính'] : 'Quản lý tài chính';
  }, [theme, language]);

  const persist = useCallback((next: { theme: AppTheme; language: AppLanguage }) => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(next));
      setError('');
      return true;
    } catch (saveError) {
      setError(`Could not save preferences: ${saveError instanceof Error ? saveError.message : String(saveError)}`);
      return false;
    }
  }, []);
  const setTheme = useCallback((next: AppTheme) => {
    if (persist({ theme: next, language })) setThemeState(next);
  }, [language, persist]);
  const setLanguage = useCallback((next: AppLanguage) => {
    if (persist({ theme, language: next })) setLanguageState(next);
  }, [persist, theme]);
  const value = useMemo<Preferences>(() => ({
    theme, language, error, setTheme, setLanguage,
    t: (text) => language === 'en' ? translateEnglish(text) : text,
  }), [theme, language, error, setTheme, setLanguage]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error('usePreferences must be used within PreferencesProvider.');
  return value;
}
